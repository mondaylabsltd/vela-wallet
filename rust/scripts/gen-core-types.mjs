#!/usr/bin/env node
/**
 * Generate the TypeScript mirrors of every Crux core's wire types.
 *
 * The Rust enums in `rust/crates/vela-core/src/app/` are the source of truth;
 * `ts-rs` emits one `.ts` file per type into each target's committed
 * `generated/` directory. Committed, because the web shell must typecheck a
 * fresh checkout without a Rust toolchain.
 *
 * One registry, one bin per app family (spec 016 research.md D3) — adding a
 * machine family is one entry here plus its generator bin. Targets generate
 * independently so an onboarding wire change never churns the wallet-state
 * output or vice versa.
 *
 * Each target writes ONE mirror, under `app-web/vela-wallet` (the only
 * TypeScript shell since spec 039 retired the Expo client). `outDirs` is
 * still a list: a second TypeScript consumer would be one more entry, and
 * two copies of a wire type that can drift apart is exactly the bug this
 * generator exists to prevent — one generation, N identical mirrors.
 *
 * Usage:
 *   node rust/scripts/gen-core-types.mjs                     write all targets
 *   node rust/scripts/gen-core-types.mjs --check             verify all (CI); non-zero on drift
 *   node rust/scripts/gen-core-types.mjs onboarding          one target by name
 *   node rust/scripts/gen-core-types.mjs wallet-state --check
 *
 * `--check` generates into a temporary directory and compares byte-for-byte,
 * so it never leaves a half-written state behind on failure.
 */

import { execFileSync } from 'node:child_process';
import { mkdtempSync, readdirSync, readFileSync, rmSync, mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const RUST_DIR = dirname(dirname(fileURLToPath(import.meta.url)));
const REPO_ROOT = dirname(RUST_DIR);

const TARGETS = [
  {
    name: 'onboarding',
    bin: 'generate_onboarding_bindings',
    outDirs: [
      join(REPO_ROOT, 'app-web', 'vela-wallet', 'src', 'lib', 'onboarding', 'generated'),
    ],
    // The committed 011 output carries the original generator's name; kept
    // byte-identical (016 FR-017).
    barrelHeader: '// @generated by rust/scripts/gen-onboarding-types.mjs — do not edit.',
  },
  {
    // The session machine alone, for shells that have wired onboarding but not
    // the other 22 wallet-state machines. The same Rust types are also part of
    // the wallet-state target below; both are generated, so they cannot drift.
    name: 'session',
    bin: 'generate_session_bindings',
    outDirs: [
      join(REPO_ROOT, 'app-web', 'vela-wallet', 'src', 'lib', 'session', 'generated'),
    ],
    barrelHeader: '// @generated by rust/scripts/gen-core-types.mjs — do not edit.',
  },
  {
    name: 'wallet-state',
    bin: 'generate_wallet_state_bindings',
    outDirs: [
      // One shared dir (spec 024), so every executor keeps its import shape.
      join(REPO_ROOT, 'app-web', 'vela-wallet', 'src', 'lib', 'core', 'generated'),
    ],
    barrelHeader: '// @generated by rust/scripts/gen-core-types.mjs — do not edit.',
  },
];

const args = process.argv.slice(2);
const CHECK_ONLY = args.includes('--check');
const names = args.filter((a) => a !== '--check');
const selected = names.length
  ? TARGETS.filter((t) => names.includes(t.name))
  : TARGETS;
if (names.length && selected.length !== names.length) {
  const known = TARGETS.map((t) => t.name).join(', ');
  console.error(`gen-core-types: unknown target in [${names.join(', ')}] — known: ${known}`);
  process.exit(1);
}

function generateInto(target, dir) {
  execFileSync(
    'cargo',
    [
      'run', '--quiet',
      '--manifest-path', join(RUST_DIR, 'Cargo.toml'),
      '-p', 'vela-core',
      '--features', 'bindings',
      '--bin', target.bin,
      '--', dir,
    ],
    { cwd: RUST_DIR, stdio: ['ignore', 'ignore', 'inherit'] },
  );
}

function readDir(dir) {
  if (!existsSync(dir)) return {};
  return Object.fromEntries(
    readdirSync(dir)
      .filter((name) => name.endsWith('.ts'))
      .sort()
      .map((name) => [name, readFileSync(join(dir, name), 'utf8')]),
  );
}

/** A barrel so call sites import from one path instead of a dozen. */
function writeIndex(target, dir) {
  const types = readdirSync(dir)
    .filter((name) => name.endsWith('.ts') && name !== 'index.ts')
    .sort();
  writeFileSync(
    join(dir, 'index.ts'),
    target.barrelHeader + '\n' +
      types.map((name) => `export * from './${name.replace(/\.ts$/, '')}';`).join('\n') +
      '\n',
  );
}

function check(target) {
  const staging = mkdtempSync(join(tmpdir(), `vela-${target.name}-types-`));
  try {
    generateInto(target, staging);
    writeIndex(target, staging); // the barrel is part of the output, so it is part of the check
    const fresh = readDir(staging);
    let ok = true;

    for (const outDir of target.outDirs) {
      const committed = readDir(outDir);
      const missing = Object.keys(fresh).filter((name) => !(name in committed));
      const extra = Object.keys(committed).filter((name) => !(name in fresh));
      const changed = Object.keys(fresh).filter(
        (name) => name in committed && committed[name] !== fresh[name],
      );

      if (missing.length || extra.length || changed.length) {
        const detail = [
          ...missing.map((n) => `  ${n}: missing from the committed output`),
          ...extra.map((n) => `  ${n}: committed but no longer generated`),
          ...changed.map((n) => `  ${n}: differs from a fresh generation`),
        ].join('\n');
        console.error(
          `gen-core-types --check [${target.name}] ${outDir}:\n` +
            `the committed TypeScript does not match the Rust wire types.\n` +
            detail +
            `\n\nRun \`npm run gen:core-types\` and commit the result.`,
        );
        ok = false;
      }
    }
    if (ok) {
      console.log(
        `gen-core-types --check [${target.name}]: ${Object.keys(fresh).length} generated types are current in ` +
          `${target.outDirs.length} mirror(s)`,
      );
    }
    return ok;
  } finally {
    rmSync(staging, { recursive: true, force: true });
  }
}

function write(target) {
  // Generate ONCE, then mirror. Running the generator per directory would let
  // two mirrors of the same wire type disagree if a run failed halfway.
  const staging = mkdtempSync(join(tmpdir(), `vela-${target.name}-types-`));
  try {
    generateInto(target, staging);
    writeIndex(target, staging);
    const fresh = readDir(staging);

    for (const outDir of target.outDirs) {
      mkdirSync(outDir, { recursive: true });
      // Remove stale files first: a renamed Rust type would otherwise leave
      // its old mirror behind, and a stale mirror still typechecks.
      for (const name of readdirSync(outDir).filter((n) => n.endsWith('.ts'))) {
        rmSync(join(outDir, name));
      }
      for (const [name, contents] of Object.entries(fresh)) {
        writeFileSync(join(outDir, name), contents);
      }
      console.log(
        `gen-core-types [${target.name}]: wrote ${Object.keys(fresh).length} files to ${outDir}`,
      );
    }
  } finally {
    rmSync(staging, { recursive: true, force: true });
  }
}

if (CHECK_ONLY) {
  const ok = selected.map(check).every(Boolean);
  process.exit(ok ? 0 : 1);
} else {
  selected.forEach(write);
}
