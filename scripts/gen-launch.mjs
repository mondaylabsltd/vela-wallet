// --- timeline vectors ----------------------------------------------------------

/**
 * CSS cubic-bezier(x1, y1, x2, y2) at progress x, solved to well below a pixel:
 * the reference every platform's own easing is held to.
 */
function cubicBezier([x1, y1, x2, y2], x) {
	const at = (a, b, t) => 3 * a * t * (1 - t) ** 2 + 3 * b * t * t * (1 - t) + t ** 3;
	let lo = 0;
	let hi = 1;
	for (let i = 0; i < 60; i++) {
		const mid = (lo + hi) / 2;
		if (at(x1, x2, mid) < x) lo = mid;
		else hi = mid;
	}
	return at(y1, y2, (lo + hi) / 2);
}

function vectors() {
	const tween = (start, end, t) =>
		cubicBezier(scene.easing, Math.min(Math.max((t - start) / (end - start), 0), 1));
	const times = [];
	for (let t = 0; t <= ms(frames); t += 50) times.push(t);
	times.push(ms(31), ms(47), ms(65));
	times.sort((a, b) => a - b);
	const r = (n) => Number(n.toFixed(6));
	const cases = times.map((t) => {
		const p = tween(ms(mark.startFrame), ms(mark.endFrame), t);
		return {
			ms: r(t),
			mark: {
				x: r(mark.from[0] + (mark.to[0] - mark.from[0]) * p),
				y: r(mark.from[1] + (mark.to[1] - mark.from[1]) * p)
			},
			letters: letters.map((l) => r(tween(ms(l.start), ms(l.end), t)))
		};
	});
	return (
		JSON.stringify(
			{
				about: `GENERATED by scripts/gen-launch.mjs from ${SOURCE}. The launch timeline sampled: where the mark is (phone canvas) and how opaque each letter is, at each time. Every platform's test holds its own easing and timeline to these; the web's Web Animations rendering was compared pixel for pixel with the Lottie files it replaced (2026-11-14) and matched them to under 0.2/255 on average.`,
				easing: scene.easing,
				cases
			},
			null,
			'\t'
		) + '\n'
	);
}

const OUTPUTS = [
	['docs/design/onboarding/launch/launch-timeline.vectors.json', vectors()],
	['app-web/vela-wallet/src/lib/launch/generated/scene.ts', web()],
	['app-ios/VelaWallet/VelaWallet/DesignSystem/LaunchScene.swift', swift()],
	[
		'app-android/vela-wallet/app/src/main/java/app/getvela/wallet/core/designsystem/tokens/VelaLaunchScene.kt',
		kotlin()
	],
	['app-desktop/vela-wallet/src/ui/launch_scene.rs', rust()]
];

const check = process.argv.includes('--check');
let stale = 0;
for (const [path, text] of OUTPUTS) {
	const target = join(root, path);
	let current = null;
	try {
		current = readFileSync(target, 'utf8');
	} catch {
		/* not written yet */
	}
	if (current === text) continue;
	if (check) {
		console.error(`gen-launch --check: ${path} is not what ${SOURCE} generates`);
		stale++;
	} else {
		writeFileSync(target, text);
		console.log(`gen-launch: wrote ${path}`);
	}
}
if (stale) {
	console.error('Run `npm --prefix scripts run gen:launch` and commit the result.');
	process.exit(1);
}
if (check) console.log(`gen-launch --check: ${OUTPUTS.length} scenes current`);
