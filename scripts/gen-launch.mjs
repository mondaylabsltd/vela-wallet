#!/usr/bin/env node
/**
 * Generate each platform's launch scene from the one description of it.
 *
 *   node scripts/gen-launch.mjs [--check]
 *
 * Source: `docs/design/onboarding/launch/launch-scene.json` — the Vela mark and
 * the wordmark as vector paths, their colours in each appearance, and the
 * timeline (the mark slides from the centre to its place, the letters fade in
 * one after another). It replaced the eight Lottie files on 2026-11-14: a
 * wallet does not need an animation runtime (lottie-web, lottie-ios,
 * lottie-compose, dotlottie-rs) to draw thirteen shapes and two kinds of
 * tween, and every platform already has a vector and an animation API.
 *
 * Output, one file per platform, drawn by that platform's own APIs:
 *   web      app-web/vela-wallet/src/lib/launch/generated/scene.ts  (SVG + Web Animations)
 *   iOS      app-ios/VelaWallet/VelaWallet/DesignSystem/LaunchScene.swift  (SwiftUI Path)
 *   Android  app-android/.../core/designsystem/tokens/VelaLaunchScene.kt   (Compose Path)
 *   desktop  app-desktop/vela-wallet/src/ui/launch_scene.rs    (gpui PathBuilder)
 *
 * The web keeps the paths as SVG `d` text, which the browser draws as is; the
 * native files carry them as typed path operations, so no platform parses
 * anything at run time and there is no load that can fail.
 *
 * Paths fill with the NONZERO rule on every platform: the crossbars of "e" and
 * "t" are separate contours wound the same way as the letter, and even-odd
 * would cut them out where they overlap.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'docs/design/onboarding/launch/launch-scene.json';
const scene = JSON.parse(readFileSync(join(root, SOURCE), 'utf8'));

// --- the scene, checked ------------------------------------------------------

const fail = (message) => {
	console.error(`gen-launch: ${message}`);
	process.exit(1);
};

/** `M x y`, `L x y`, `C x1 y1 x2 y2 x y`, `Z` — absolute, which is all the scene uses. */
function parse(d, where) {
	const tokens = d.trim().split(/[\s,]+|(?=[MLCZ])|(?<=[MLCZ])/).filter(Boolean);
	const ops = [];
	const arity = { M: 2, L: 2, C: 6, Z: 0 };
	for (let i = 0; i < tokens.length; ) {
		const cmd = tokens[i++];
		if (!(cmd in arity)) fail(`${where}: "${cmd}" is not M, L, C or Z (absolute commands only)`);
		const args = tokens.slice(i, i + arity[cmd]).map(Number);
		if (args.length !== arity[cmd] || args.some((n) => !Number.isFinite(n)))
			fail(`${where}: ${cmd} needs ${arity[cmd]} numbers`);
		i += arity[cmd];
		ops.push([cmd, ...args]);
	}
	if (ops[0]?.[0] !== 'M') fail(`${where}: a path starts with M`);
	return ops;
}

const ROLES = ['wordmark', 'sunset', 'peach', 'hull'];
for (const appearance of ['dark', 'light']) {
	for (const role of ROLES) {
		if (!/^#[0-9A-F]{6}$/.test(scene.colors?.[appearance]?.[role] ?? ''))
			fail(`colors.${appearance}.${role} must be #RRGGBB`);
	}
}
const frames = scene.durationFrames;
const ms = (frame) => (frame * 1000) / scene.fps;
const { mark, wordmark } = scene;
if (!(mark.startFrame < mark.endFrame && mark.endFrame <= frames)) fail('the mark moves inside the timeline');
const markPaths = mark.paths.map((p, i) => {
	if (!ROLES.includes(p.fill)) fail(`mark.paths[${i}].fill "${p.fill}" is not a colour role`);
	return { fill: p.fill, ops: parse(p.d, `mark.paths[${i}]`), d: p.d };
});
const letters = wordmark.letters.map((l, i) => {
	const end = l.startFrame + wordmark.fadeFrames;
	if (end > frames) fail(`letter ${i} ("${l.glyph}") fades in after the timeline ends`);
	return { glyph: l.glyph, start: l.startFrame, end, ops: parse(l.d, `letter ${i}`), d: l.d };
});
const last = Math.max(mark.endFrame, ...letters.map((l) => l.end));

// --- number formatting -------------------------------------------------------

/** Shortest text that reads back as the same number; always a float literal. */
const f = (n) => {
	const s = String(Number(n.toFixed(6)));
	return s.includes('.') || s.includes('e') ? s : `${s}.0`;
};
const msText = (frame) => f(Number(ms(frame).toFixed(6)));
const hex = (c) => c.slice(1).toUpperCase();

const HEADER = (comment) =>
	[
		`${comment} GENERATED by scripts/gen-launch.mjs from ${SOURCE}.`,
		`${comment} Do not edit: change the scene there and run \`npm --prefix scripts run gen:launch\`.`,
		`${comment}`,
		`${comment} The launch lockup: the Vela mark slides from the centre to its place while the`,
		`${comment} wordmark's letters fade in one after another. Coordinates are the phone`,
		`${comment} canvas's (${scene.canvas.w} × ${scene.canvas.h}); the large-screen canvas (${scene.largeScreen.w} × ${scene.largeScreen.h}) draws the`,
		`${comment} same scene scaled ${scene.largeScreen.scale}× at (${scene.largeScreen.offset.join(', ')}). Times are milliseconds from the`,
		`${comment} start; every tween uses \`easing\` (a CSS cubic-bezier). Fill rule: nonzero.`
	].join('\n');

// --- web -----------------------------------------------------------------------

function web() {
	const msText = (frame) => String(Number(ms(frame).toFixed(6)));
	const color = (a) => `{ ${ROLES.map((r) => `${r}: '${scene.colors[a][r]}'`).join(', ')} }`;
	return `${HEADER('//')}

export const SCENE = {
	durationMs: ${msText(frames)},
	/** When the last tween ends; the rest of \`durationMs\` is the finished lockup, still. */
	settledMs: ${msText(last)},
	easing: 'cubic-bezier(${scene.easing.join(', ')})',
	canvas: { w: ${scene.canvas.w}, h: ${scene.canvas.h} },
	largeScreen: {
		w: ${scene.largeScreen.w},
		h: ${scene.largeScreen.h},
		scale: ${scene.largeScreen.scale},
		offset: { x: ${scene.largeScreen.offset[0]}, y: ${scene.largeScreen.offset[1]} }
	},
	fullBleed: {
		phone: { w: ${scene.fullBleed.phone.w}, h: ${scene.fullBleed.phone.h} },
		largeScreen: { w: ${scene.fullBleed.largeScreen.w}, h: ${scene.fullBleed.largeScreen.h} }
	},
	colors: {
		dark: ${color('dark')},
		light: ${color('light')}
	},
	mark: {
		from: { x: ${mark.from[0]}, y: ${mark.from[1]} },
		to: { x: ${mark.to[0]}, y: ${mark.to[1]} },
		startMs: ${msText(mark.startFrame)},
		endMs: ${msText(mark.endFrame)},
		paths: [
${markPaths.map((p) => `\t\t\t{ fill: '${p.fill}', d: '${p.d}' }`).join(',\n')}
		]
	},
	letters: [
${letters.map((l) => `\t\t{ glyph: '${l.glyph}', startMs: ${msText(l.start)}, endMs: ${msText(l.end)}, d: '${l.d}' }`).join(',\n')}
	]
} as const;

export type ColorRole = keyof (typeof SCENE)['colors']['dark'];
`;
}

// --- native op lists -----------------------------------------------------------

function opsList(ops, { move, line, curve, close }, indent) {
	return ops
		.map(([cmd, ...a]) => {
			const n = a.map(f);
			if (cmd === 'M') return move(n);
			if (cmd === 'L') return line(n);
			if (cmd === 'C') return curve(n);
			return close;
		})
		.map((s) => indent + s)
		.join(',\n');
}

