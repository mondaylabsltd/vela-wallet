#!/usr/bin/env node
/**
 * Generate the passkey-provider catalog from the vendored AAGUID dataset.
 *
 *   node scripts/gen-passkey-providers.mjs [--check]
 *
 * Source: `rust/crates/vela-core/data/passkey-providers.json`, vendored from
 * the community dataset at
 * https://github.com/passkeydeveloper/passkey-authenticator-aaguids
 * (the same catalog aaguid-explorer.awesometools.dev serves). It is VENDORED
 * rather than fetched because a wallet must not ask a third party which
 * authenticator its owner uses — the AAGUID says what kind of vault holds the
 * key, and that is nobody else's business. Refreshing it is a deliberate,
 * reviewable commit, not a runtime call.
 *
 * Output: `rust/crates/vela-core/src/passkey_catalog.rs` — one table for all
 * four clients, because the alternative is four drifting copies of a list of
 * brand names.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(root, 'rust/crates/vela-core/data/passkey-providers.json');
const TARGET = join(root, 'rust/crates/vela-core/src/passkey_catalog.rs');
const NONE = 65535; // u16::MAX — "this provider ships no icon for that theme"

const data = JSON.parse(readFileSync(SOURCE, 'utf8'));
const aaguids = Object.keys(data).sort();

/** Icons are deduplicated: 36 of 55 providers draw the same mark in both themes. */
const icons = [];
const index = new Map();
const intern = (svg) => {
	if (svg === undefined) return NONE;
	if (!index.has(svg)) {
		index.set(svg, icons.length);
		icons.push(svg);
	}
	return index.get(svg);
};

const rows = aaguids.map((aaguid) => {
	if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(aaguid)) {
		throw new Error(`not a canonical lowercase uuid: ${aaguid}`);
	}
	const entry = data[aaguid];
	return { aaguid, name: entry.name, light: intern(entry.light), dark: intern(entry.dark) };
});

const rust = (value) => JSON.stringify(value); // Rust and JSON agree on "…\"…\\…"

const out = `//! @generated by \`scripts/gen-passkey-providers.mjs\` — do not edit.
//!
//! Vendored from https://github.com/passkeydeveloper/passkey-authenticator-aaguids
//! (${rows.length} providers, ${icons.length} distinct marks). Regenerate with
//! \`npm run gen:passkey-providers\` after refreshing
//! \`data/passkey-providers.json\`.

/// Distinct icon markup, referenced by index from [\`PROVIDERS\`].
pub(crate) static ICONS: [&str; ${icons.length}] = [
${icons.map((svg) => `    ${rust(svg)},`).join('\n')}
];

/// \`(aaguid, name, light icon, dark icon)\`, sorted by aaguid for binary search.
/// An icon index of [\`NO_ICON\`] means the provider ships no mark for that theme.
pub(crate) static PROVIDERS: [(&str, &str, u16, u16); ${rows.length}] = [
${rows.map((r) => `    (${rust(r.aaguid)}, ${rust(r.name)}, ${r.light}, ${r.dark}),`).join('\n')}
];

/// Sentinel index for "no icon in this theme".
pub(crate) const NO_ICON: u16 = ${NONE};
`;

/**
 * rustfmt, the way the repository will see this file anyway.
 *
 * Without this the generator emitted one-line tuples, `cargo fmt` wrapped the
 * long ones, and `--check` then called a byte-identical catalog "stale" — on
 * `main`, for anyone who ran the documented gate. Regenerating to silence it
 * produced a 198-line diff that changed nothing but whitespace. Formatting
 * here makes the comparison mean what it says again.
 */
function formatted(source) {
	try {
		return execFileSync('rustfmt', ['--emit', 'stdout', '--edition', '2024', '--quiet'], {
			input: source,
			encoding: 'utf8'
		});
	} catch {
		// No rustfmt (or it refused): compare what we generated, unformatted.
		// A missing toolchain must not turn this gate into a false alarm of
		// its own — it just makes it weaker, and says so.
		console.warn('rustfmt unavailable — comparing unformatted output');
		return source;
	}
}

const check = process.argv.includes('--check');
const text = formatted(out);
if (check) {
	const current = readFileSync(TARGET, 'utf8');
	if (current !== text) {
		console.error('passkey catalog is stale — run `npm run gen:passkey-providers`');
		process.exit(1);
	}
	console.log(`passkey catalog in sync (${rows.length} providers, ${icons.length} marks)`);
} else {
	writeFileSync(TARGET, text);
	console.log(`wrote ${TARGET} (${rows.length} providers, ${icons.length} marks)`);
}
